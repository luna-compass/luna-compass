# tabs/guide.py
# タブ5：星からのガイド

import streamlit as st


def show(tab):
    with tab:
        st.markdown("## 📖 星からのガイド")

        st.markdown("### ☺ ASC（第一印象）")
        st.markdown("""
人生の入り口に宿るエネルギー。
あなたが自然に放つ雰囲気や、
人が最初に感じ取る空気を映し出します。

この世界とどう関わり、
どんな扉を開いていくのかを示す大切なポイントです。
""")

        st.markdown("### ☀ 太陽（本質）")
        st.markdown("""
人生を照らす中心の光。
あなたらしさと、生きる方向性を映し出します。

情熱・誇り・存在感は、
魂がこの人生で輝くための力です。
""")

        st.markdown("### ☽ 月（感情）")
        st.markdown("""
心の奥で静かに揺れる感情。
安心できる場所や、
素のあなたを映し出します。

感情の流れは、
魂が安らぎを求める方向を教えてくれます。
""")

        st.markdown("### ☿ 水星（思考）")
        st.markdown("""
知識をつなぐ魂。
好奇心と観察力で世界を読み解き、
人と人・過去と未来を結ぶ存在。

学び・言葉・探究は、
あなたの宿命であり才能です。
""")

        st.markdown("### ♀ 金星（愛情）")
        st.markdown("""
心が美しいと感じるもの。
愛し方や魅力、
心地よさの感覚を表します。

喜びや愛情は、
人生を豊かに彩る優しい光です。
""")

        st.markdown("### ♂ 火星（行動）")
        st.markdown("""
内側から燃え上がる行動の炎。
情熱・決断力・前へ進む力を表します。

あなたが何に向かって力を使い、
どう世界を切り開いていくのかを示します。
""")

        st.markdown("### ♃ 木星（発展）")
        st.markdown("""
可能性を広げる幸運の星。
成長・発展・希望の方向を示します。

新しい世界へ踏み出す時、
木星は未来への扉を開いてくれます。
""")

        st.markdown("### ♄ 土星（課題）")
        st.markdown("""
時間をかけて育てる魂のテーマ。
責任・試練・人生の課題を表します。

簡単ではないからこそ、
そこには本物の強さと深みが宿ります。
""")

        st.markdown("<br><br>", unsafe_allow_html=True)
        st.markdown("### 🏠 ハウスの意味ガイド")

        HOUSE_GUIDE = {
            1: "自分自身・性格・第一印象の領域です。",
            2: "お金・才能・所有・価値観の領域です。",
            3: "学び・コミュニケーション・兄弟姉妹の領域です。",
            4: "家・家族・ルーツ・安心できる場所の領域です。",
            5: "恋愛・創造性・趣味・自己表現の領域です。",
            6: "仕事・健康・日々の習慣の領域です。",
            7: "パートナーシップ・契約・対人関係の領域です。",
            8: "心の深い結びつき・共有資産・変容の領域です。",
            9: "哲学・専門的学び・海外・精神性の領域です。",
            10: "社会的地位・キャリア・使命の領域です。",
            11: "仲間・コミュニティ・未来のビジョンの領域です。",
            12: "潜在意識・癒し・見えない世界の領域です。",
        }

        for house_num, msg in HOUSE_GUIDE.items():
            st.markdown(f"### {house_num}ハウス")
            st.markdown(
                f"<div class='luna-message'>{msg}</div>",
                unsafe_allow_html=True
            )
