def get_hexagram(number):
    for h in HEXAGRAMS:
        if h["number"] == number:
            return h
    return HEXAGRAMS[0]


def draw_hexagram():
    """ランダムに一卦を引く（コイン投げ方式）"""
    # 6本の爻を決定（0=陰、1=陽）
    lines = [random.randint(0, 1) for _ in range(6)]
    # 卦番号を1〜64からランダムに選択
    number = random.randint(1, 64)
    return get_hexagram(number)


