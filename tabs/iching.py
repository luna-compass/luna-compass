def _render():
    st.markdown("### 🔯 易占い（六十四卦）")
    st.caption("コインを3枚投げるように、卦を立ててメッセージを受け取りましょう。")

    theme = st.radio(
        "🔯 テーマを選んでください",
        ["総合", "恋愛", "仕事"],
        horizontal=True,
        key="iching_theme"
    )

    st.markdown("---")

    if st.button("🔯 卦を立てる", use_container_width=True, type="primary", key="btn_iching"):
        hexagram = draw_hexagram()

        st.markdown(f"### {hexagram['symbol']} {hexagram['name']}（{hexagram['yomi']}）")
        st.markdown(f"**第{hexagram['number']}卦　{hexagram['keyword']}**")

        st.markdown("---")
        st.markdown("**📖 卦のメッセージ**")
        for line in hexagram["message"].split("\n"):
            if line.strip():
                st.markdown(f"<div class='luna-message'>{line}</div>", unsafe_allow_html=True)

        st.markdown("---")
        if theme == "恋愛":
            st.markdown("**💕 恋愛へのメッセージ**")
            st.markdown(f"<div class='luna-message'>{hexagram['love']}</div>", unsafe_allow_html=True)
        elif theme == "仕事":
            st.markdown("**💼 仕事へのメッセージ**")
            st.markdown(f"<div class='luna-message'>{hexagram['work']}</div>", unsafe_allow_html=True)
        else:
            st.markdown("**💕 恋愛へのヒント**")
            st.markdown(f"<div class='luna-message'>{hexagram['love']}</div>", unsafe_allow_html=True)
            st.markdown("**💼 仕事へのヒント**")
            st.markdown(f"<div class='luna-message'>{hexagram['work']}</div>", unsafe_allow_html=True)

        st.markdown("---")
        st.caption(f"第{hexagram['number']}卦　{hexagram['name']}（{hexagram['yomi']}）")
